"""
inference/__init__.py
=====================
Core dataclasses for the OA detection inference pipeline.

Defines the structured output types produced during a full analysis run:

- ``RiskMarkerResult``  – per-marker status with confidence and provenance note.
- ``RiskMarkersReport`` – aggregation of all six OA risk marker assessments.
- ``OAAnalysisResult``  – top-level result object returned by :class:`OAPredictor`.

All results carry an explicit medical disclaimer and a
``requires_clinical_review = True`` flag to emphasise that no output from
this system replaces evaluation by a qualified radiologist or clinician.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional

import numpy as np

# ---------------------------------------------------------------------------
# Re-export companion dataclasses so callers can import from a single place.
# ---------------------------------------------------------------------------
